/** Colours that tell the three kinds of money apart everywhere in the app. */
object KindColors {
    fun accent(type: String, dark: Boolean): Color = when (type) {
        TxnType.INCOME -> if (dark) Color(0xFF7FD6B4) else Color(0xFF0B6E4F)
        TxnType.INVEST -> if (dark) Color(0xFFA9B8FF) else Color(0xFF3A4FB8)
        else -> if (dark) Color(0xFFFFB68C) else Color(0xFFB4541A)
    }

    fun container(type: String, dark: Boolean): Color = when (type) {
        TxnType.INCOME -> if (dark) Color(0xFF0B3D2E) else Color(0xFFD6F0E4)
        TxnType.INVEST -> if (dark) Color(0xFF232C55) else Color(0xFFE0E5FF)
        else -> if (dark) Color(0xFF4A2610) else Color(0xFFFFE6D6)
    }
}

/** A category icon in a tinted circle. */
@Composable
fun CategoryBadge(icon: String?, type: String, size: Dp = 42.dp) {
    val dark = androidx.compose.foundation.isSystemInDarkTheme()
    Box(
        Modifier.size(size).clip(CircleShape).background(KindColors.container(type, dark)),
        contentAlignment = Alignment.Center,
    ) {
        Icon(
            painterResource(CategoryIcons.res(icon)),
            contentDescription = null,
            tint = KindColors.accent(type, dark),
            modifier = Modifier.size(size * 0.52f),
        )
    }
}

fun kindLabel(type: String) = when (type) {
    TxnType.INCOME -> "Income"
    TxnType.INVEST -> "Investing"
    else -> "Spending"
}
