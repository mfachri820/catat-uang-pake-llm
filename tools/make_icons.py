# A receipt with a zig-zag tear, a rising line (money tracked over time) and a gold coin.
def zigzag(x0, x1, y, depth=5, teeth=5):
    w = (x1 - x0) / (teeth * 2)
    pts = []
    x = x1
    for i in range(teeth * 2):
        x -= w
        pts.append(f"L{x:.2f},{y - depth if i % 2 == 0 else y:.2f}")
    return " ".join(pts)

