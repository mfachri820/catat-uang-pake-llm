def vector_xml(paths):
    body = "\n".join(
        f'    <path\n        android:pathData="{p}"\n        android:strokeColor="#FF000000"\n'
        f'        android:strokeWidth="2"\n        android:strokeLineCap="round"\n        android:strokeLineJoin="round" />'
        for p in paths
    )
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/make_icons.py -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="24dp"\n    android:height="24dp"\n'
            '    android:viewportWidth="24"\n    android:viewportHeight="24">\n' + body + "\n</vector>\n")

def svg_icon(paths, size=72, color="#0B6E4F"):
    inner = "".join(f'<path d="{p}" fill="none" stroke="{color}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/>' for p in paths)
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 24 24">{inner}</svg>'

